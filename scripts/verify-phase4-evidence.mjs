import { createHash } from "node:crypto";
import { readFile } from "node:fs/promises";
import { resolve } from "node:path";

const root = resolve(import.meta.dirname, "..");
const feltPattern = /^0x[0-9a-f]+$/;
const digestPattern = /^0x[0-9a-f]{64}$/;

async function readJson(path) {
  return JSON.parse(await readFile(resolve(root, path), "utf8"));
}

function assert(condition, message) {
  if (!condition) throw new Error(message);
}

function assertFelt(value, label) {
  assert(typeof value === "string" && feltPattern.test(value) && BigInt(value) !== 0n,
    `${label} is not a nonzero Starknet felt.`);
}

function assertDigest(value, label) {
  assert(typeof value === "string" && digestPattern.test(value),
    `${label} is not a canonical 32-byte digest.`);
}

function sha256(value) {
  return createHash("sha256").update(value).digest("hex");
}

const [privatePayroll, policyLifecycle, browser] = await Promise.all([
  readJson("evidence/phase4-private-payroll-devnet.json"),
  readJson("evidence/phase4-policy-account-devnet.json"),
  readJson("evidence/phase4-rendered-browser-ui-origin.json"),
]);

assert(privatePayroll.schemaVersion === "payo.phase4.private-payroll-devnet.v1",
  "Phase 4 private-payroll evidence has the wrong schema.");
assert(privatePayroll.chainId === "0x534e5f5345504f4c4941",
  "Phase 4 private-payroll evidence is not bound to SN_SEPOLIA Devnet.");
assert(privatePayroll.proofMode === "none",
  "Phase 4 Devnet evidence must state its transaction-proof mode explicitly.");
assert(privatePayroll.proofs?.settlementProver === "remote-self-hosted",
  "SettlementMatch was not generated by the self-hosted remote prover.");
assert(privatePayroll.proofs?.sdkProofFactsPresent === true,
  "The SDK result contains no proof facts.");
assert(privatePayroll.proofs?.sdkTransactionProofBytesPresent === false,
  "The committed Devnet profile changed transaction-proof semantics unexpectedly.");
assert(Array.isArray(privatePayroll.limitations)
  && privatePayroll.limitations.some((value) => value.includes("not full transaction-OS proof evidence")),
"The Devnet transaction-proof limitation is missing.");

const circuit = await readFile(resolve(root, "public/circuits/settlement_match-v8.json"));
const verificationKeyHex = (await readFile(
  resolve(root, "public/circuits/settlement_match-v8.vk.hex"),
  "utf8",
)).replace(/\s/g, "");
assert(/^[0-9a-f]+$/i.test(verificationKeyHex) && verificationKeyHex.length % 2 === 0,
  "The committed SettlementMatch verification key is malformed.");
assert(privatePayroll.proofs?.settlementMatch?.circuitSha256 === `0x${sha256(circuit)}`,
  "SettlementMatch evidence is not bound to the committed circuit.");
assert(
  privatePayroll.proofs?.settlementMatch?.verificationKeySha256
    === `0x${sha256(Buffer.from(verificationKeyHex, "hex"))}`,
  "SettlementMatch evidence is not bound to the committed verification key.",
);
assert(Number.isInteger(privatePayroll.proofs?.settlementMatch?.provingTimeMs)
  && privatePayroll.proofs.settlementMatch.provingTimeMs > 0,
"SettlementMatch proving-time evidence is invalid.");
assertFelt(privatePayroll.proofs?.settlementMatch?.calldataHash,
  "SettlementMatch calldata hash");
assertDigest(privatePayroll.run?.manifestRoot, "Manifest root");
assertDigest(privatePayroll.run?.runNullifier, "Run nullifier");
assertDigest(privatePayroll.run?.settlementRoot, "Settlement root");
assertDigest(privatePayroll.run?.transactionReference, "Transaction reference");

const requiredChecks = [
  "payrollIntegrityPrecommittedBeforePayment",
  "bothPayrollIntegrityShardsVerifiedBeforePayment",
  "payrollIntegrityProvenBeforePayment",
  "exactSdkCiphertextExtractedBeforeSettlementProof",
  "settlementMatchVerifiedOnchain",
  "privatePaymentAndFinalizationAtomic",
  "policyScopeAndAuthorizedRunEnforced",
  "recipientPrivateNoteDiscovered",
  "recipientBalanceDeltaExact",
  "settlementReceiptMatchesProof",
  "sealFinalized",
  "replayRejected",
];
for (const check of requiredChecks) {
  assert(privatePayroll.checks?.[check] === true, `Phase 4 evidence check ${check} did not pass.`);
}

const amount = BigInt(privatePayroll.run?.amountAtomic);
const before = BigInt(privatePayroll.privateBalanceEvidenceAtomic?.recipientBefore);
const after = BigInt(privatePayroll.privateBalanceEvidenceAtomic?.recipientAfter);
const delta = BigInt(privatePayroll.privateBalanceEvidenceAtomic?.delta);
assert(amount > 0n && delta === amount && after - before === amount,
  "The private recipient balance delta does not equal the approved payroll amount.");
assert(Number.isInteger(privatePayroll.settlementBlockNumber)
  && privatePayroll.settlementBlockNumber > 0,
"The finalized settlement block is invalid.");
for (const [name, contract] of Object.entries(privatePayroll.contracts ?? {})) {
  assertFelt(contract.address, `${name} address`);
  assertFelt(contract.transactionHash, `${name} deployment transaction`);
}
assert(Object.keys(privatePayroll.contracts ?? {}).length === 8,
  "The Phase 4 Devnet topology is incomplete.");
for (const [name, transaction] of Object.entries(privatePayroll.transactions ?? {})) {
  if (name === "payrollProofShards") {
    assert(Array.isArray(transaction) && transaction.length === 2,
      "PayrollIntegrity evidence must contain exactly two proof-shard transactions.");
    transaction.forEach((hash, index) => assertFelt(hash, `Payroll proof shard ${index}`));
  } else {
    assertFelt(transaction, `${name} transaction`);
  }
}

assert(policyLifecycle.scope === "phase4-policy-account-lifecycle-only",
  "Policy-account lifecycle evidence has the wrong scope.");
for (const check of ["snip6", "snip9V2", "previousOwnerRejected"]) {
  assert(policyLifecycle.account?.[check] === true, `Policy-account check ${check} did not pass.`);
}
for (const check of [
  "configured",
  "sessionRotated",
  "pauseRoundTrip",
  "ownerRecovered",
  "revoked",
]) {
  assert(policyLifecycle.policy?.[check] === true, `Policy lifecycle check ${check} did not pass.`);
}

assert(browser.schemaVersion === "payo.phase4.rendered-browser-origin.v2",
  "Phase 4 rendered-browser evidence has the wrong schema.");
assert(browser.routeGuard === "PAYO_BROWSER_EVIDENCE_MODE=1",
  "Phase 4 browser evidence is not protected by its non-production route guard.");
for (const [check, passed] of Object.entries(browser.checks ?? {})) {
  assert(passed === true, `Rendered Phase 4 check ${check} did not pass.`);
}
assert(browser.evidenceSummary?.capabilityModes?.includes("request_approval"),
  "Rendered evidence does not preserve human approval as the default path.");
assert(browser.evidenceSummary?.capabilityModes?.includes("autonomous_bounded"),
  "Rendered evidence does not include bounded autonomy.");
assert(!JSON.stringify(browser).includes("private-recipient-must-not-render"),
  "Rendered evidence leaked private recipient metadata.");
assert(!JSON.stringify(browser).includes("1000000000000000000"),
  "Rendered evidence leaked a private amount.");

process.stdout.write(
  "Phase 4 evidence verified: policy lifecycle, approval/autonomy UI, real SettlementMatch, atomic private payroll, finalization and replay rejection.\n",
);
