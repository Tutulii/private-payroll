import { createHash } from "node:crypto";
import { mkdir, readFile, writeFile } from "node:fs/promises";
import { dirname, resolve } from "node:path";
import { poseidonSmall } from "@scure/starknet";

const OUTPUT = resolve("circuits/settlement_match/src/stark_poseidon_constants.nr");
const LIMB_BITS = 120n;
const LIMB_MASK = (1n << LIMB_BITS) - 1n;
const EXPECTED_ROUNDS = 91;
const EXPECTED_WIDTH = 3;

function limbs(value) {
  const result = [];
  let remaining = value;
  for (let index = 0; index < 3; index += 1) {
    result.push(`0x${(remaining & LIMB_MASK).toString(16)}`);
    remaining >>= LIMB_BITS;
  }
  if (remaining !== 0n) throw new Error("A Stark Poseidon constant exceeds 360 bits.");
  return `[${result.join(", ")}]`;
}

const rounds = poseidonSmall.roundConstants;
if (!Array.isArray(rounds) || rounds.length !== EXPECTED_ROUNDS
  || rounds.some((round) => !Array.isArray(round) || round.length !== EXPECTED_WIDTH)) {
  throw new Error("@scure/starknet returned an unexpected Stark Poseidon profile.");
}

const body = rounds.flat().map((constant) => `    ${limbs(constant)},`).join("\n");
const source = `// Generated by scripts/generate-stark-poseidon-noir.mjs. Do not edit by hand.
// Profile: Starknet field, width 3, rate 2, 8 full + 83 partial rounds, x^3 S-box.
pub global STARK_POSEIDON_ROUND_CONSTANT_LIMBS: [[u128; 3]; 273] = [
${body}
];
`;
const digest = createHash("sha256").update(source).digest("hex");

if (process.argv.includes("--check")) {
  const current = await readFile(OUTPUT, "utf8").catch(() => "");
  if (current !== source) {
    throw new Error("Generated Stark Poseidon constants are stale. Run npm run phase4:settlement:generate.");
  }
  console.log(`Stark Poseidon constants verified (${digest}).`);
} else {
  await mkdir(dirname(OUTPUT), { recursive: true });
  await writeFile(OUTPUT, source, "utf8");
  console.log(`Wrote ${OUTPUT} (${digest}).`);
}
